function slxPath = build_rover_dual_control_model()
%BUILD_ROVER_DUAL_CONTROL_MODEL Create the dual sim + real rover model.
%
% Stage 4: teleop -> /cmd_vel (real rover) + MCL MAP pose -> Set_RoverTwin
% (Unreal twin via maps/unreal_alignment.mat).

dualMatlab = fileparts(mfilename("fullpath"));
paths = rover_dual_setup_paths(dualMatlab);
modelName = "rover_dual_control";
modelNameChar = char(modelName);
modelDir = fullfile(paths.dualRoot, "simulink");
slxPath = fullfile(modelDir, modelName + ".slx");

if ~isfolder(modelDir)
    mkdir(modelDir);
end

setup_ros_humble();
spawn = rover_spawn_pose();
cfg = rover_cmd_vel_config();
unrealProject = rover_unreal_project_alias();
spawnPosStr = mat2str(spawn.sim_m, 8);
cameraPosStr = dual_align_camera_translation(paths.projectRoot, spawn);

load_system("simulink");
load_system("drivingsim3d");
load_system("sim3dlib");
load_system("roslib");

if bdIsLoaded(modelNameChar)
    close_system(modelNameChar, 0);
end

if isfile(slxPath)
    delete(slxPath);
end

new_system(modelNameChar);
open_system(modelNameChar);

configureModel(modelNameChar);
addTeleop(modelNameChar);
addMapPosePath(modelNameChar);
addUnreal(modelNameChar, unrealProject, spawn, spawnPosStr, cameraPosStr);
addRosPublisher(modelNameChar);
wireDualOutputs(modelNameChar);
addNotes(modelNameChar);

set_param(modelNameChar, "SimulationCommand", "update");
configureRuntimeCallbacks(modelNameChar);
save_system(modelNameChar, slxPath);
set_param(modelNameChar, "ZoomFactor", "FitSystem");

fprintf("Created dual Simulink model: %s\n", slxPath);
end

function configureModel(modelName)
set_param(modelName, ...
    "SolverType", "Fixed-step", ...
    "Solver", "FixedStepDiscrete", ...
    "FixedStep", "0.1", ...
    "StopTime", "inf", ...
    "SimulationMode", "normal");
end

function configureRuntimeCallbacks(modelName)
pathBootstrap = [ ...
    'dualRoot = fileparts(fileparts(get_param(bdroot, ''FileName''))); ' ...
    'addpath(fullfile(dualRoot, ''matlab'')); ' ...
    'addpath(fullfile(fileparts(dualRoot), ''matlab'')); ' ...
    'addpath(fullfile(fileparts(dualRoot), ''roversim'', ''MATLAB'')); ' ...
    ];

set_param(modelName, ...
    "InitFcn", [pathBootstrap 'rover_dual_init();'], ...
    "StartFcn", [pathBootstrap 'rover_dual_start();'], ...
    "StopFcn", [pathBootstrap 'rover_dual_stop();']);
end

function addTeleop(modelName)
