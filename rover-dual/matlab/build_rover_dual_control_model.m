add_block("simulink/Sources/Clock", modelName + "/Teleop_Tick", ...
    "Position", [40 110 70 140]);

add_block(interpFcnBlock, modelName + "/Teleop_Linear", ...
    "MATLABFcn", "simulink_teleop_lin(u)", ...
    "Position", [115 90 245 120]);
add_block(interpFcnBlock, modelName + "/Teleop_Angular", ...
    "MATLABFcn", "simulink_teleop_ang(u)", ...
    "Position", [115 145 245 175]);

add_line(modelName, "Teleop_Tick/1", "Teleop_Linear/1", "autorouting", "on");
add_line(modelName, "Teleop_Tick/1", "Teleop_Angular/1", "autorouting", "on");

add_block("simulink/Sinks/Scope", modelName + "/Scope_Cmd_Linear", ...
    "Position", [285 90 315 120]);
add_block("simulink/Sinks/Scope", modelName + "/Scope_Cmd_Angular", ...
    "Position", [285 145 315 175]);
add_line(modelName, "Teleop_Linear/1", "Scope_Cmd_Linear/1", "autorouting", "on");
add_line(modelName, "Teleop_Angular/1", "Scope_Cmd_Angular/1", "autorouting", "on");
end

