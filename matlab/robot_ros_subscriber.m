function sub = robot_ros_subscriber(node, topic, msgType)
%ROBOT_ROS_SUBSCRIBER  QoS matched to Yahboom micro-ROS publishers.

    if strcmp(topic, '/scan')
        % Firmware publishes 360-pt LaserScan with reliable QoS (see check_robot.sh).
        sub = ros2subscriber(node, topic, msgType, ...
            'Reliability', 'reliable', ...
            'Durability', 'volatile', ...
            'Depth', 10);
    else
        sub = ros2subscriber(node, topic, msgType, ...
            'Reliability', 'reliable', ...
            'Durability', 'volatile', ...
            'Depth', 10);
    end
end

